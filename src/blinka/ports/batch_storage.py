"""Puerto de persistencia para el estado agregado de un lote."""
from __future__ import annotations
from typing import Optional, Protocol
from blinka.domain.batch_models import BatchRequest, BatchResult

class BatchStore(Protocol):
    def initialize(self) -> None: ...
    def create(self, request: BatchRequest) -> BatchResult: ...
    def save(self, result: BatchResult) -> BatchResult: ...
    def get(self, batch_id: str) -> Optional[BatchResult]: ...
